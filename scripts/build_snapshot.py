"""Build the temporary data snapshot in data/snapshot/ from the PSI files.

Writes tests.csv (every mapped PSI test row in the contract format), catalog.md
(meaning and unit of every column) and build-report.md (what was read, written
and skipped). The database owner's export replaces this folder when it exists;
it must keep the same column names (scripts/contract.py).

Usage: uv run python -m scripts.build_snapshot
"""
import csv
import json
import sys
from pathlib import Path

from scripts import contract
from scripts.cells import read_table
from scripts.mappers import MAPPERS
from scripts.paths import PSI_DIR, SNAPSHOT_DIR

CAVEATS = [
    "Oxygen is stored in percent. Mole fraction and volume fraction are treated as equal (ideal gas).",
    "A row can hold several values (FLEX-2 condition matrix, BRE test days): o2/pressure min and max then differ, and `problems` says so.",
    "FLEX headers lost their subscripts in PSI's file: `O` = O2, `N` = N2, `CO` = CO2 (FLEX tested CO2 and He as diluents).",
    "CFI-G inverse flames: the O2 value is the burner (oxidizer) stream, not the chamber.",
    "BASS-II, Saffire-II, BRE and SAME-R tables do not give a pressure; those cells are empty.",
    "Values outside physical ranges (O2 0-100 %, pressure 0-50 atm, flow 0-1000 cm/s) are left empty and noted in `problems`; the original cell stays in `raw`.",
    "Row numbers: the first data row after the header is 1. Column names are the CSV header with repeated whitespace collapsed.",
]


def write_csv(path: Path, columns: list[str], rows: list[dict]) -> None:
    """UTF-8, '\\n' line endings, None -> empty cell."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, lineterminator="\n", extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({k: ("" if row.get(k) is None else row[k]) for k in columns})


def _investigation_number(investigation: str) -> int:
    return int(investigation.split("-")[1])


def _sort_key(row: dict) -> tuple[int, int, int]:
    """Investigation number, table index, source row (test_id is PSI-25-T0-R1)."""
    table_index = int(row["test_id"].rsplit("-T", 1)[1].split("-R")[0])
    return _investigation_number(row["investigation"]), table_index, row["source_row"]


def _table_index(psi_dir: Path, investigation: str, file_name: str) -> int:
    record_path = psi_dir / f"{investigation}.json"
    if record_path.exists():
        tables = json.loads(record_path.read_text(encoding="utf-8")).get("experimentalTable", [])
        if file_name in tables:
            return tables.index(file_name)
    return 0


def build_tests(psi_dir: Path) -> tuple[list[dict], list[str]]:
    """Map every known table. Returns (rows sorted by investigation, table, row; report lines)."""
    rows: list[dict] = []
    report: list[str] = ["| Table | Rows read | Rows written | Rows skipped |", "|---|---|---|---|"]
    unmapped: list[str] = []
    for path in sorted(psi_dir.glob("PSI-*.csv")):
        mapper = MAPPERS.get(path.name)
        if mapper is None:
            unmapped.append(path.name)
            continue
        investigation = path.name.split("_")[0]
        index = _table_index(psi_dir, investigation, path.name)
        read = written = 0
        skipped: list[int] = []
        for source_row, cells in read_table(path):
            read += 1
            row = mapper(investigation, source_row, cells)
            if row is None:
                skipped.append(source_row)
                continue
            row["test_id"] = f"{investigation}-T{index}-R{source_row}"
            row["source_table"] = path.name
            rows.append(row)
            written += 1
        skipped_text = ", ".join(map(str, skipped)) if skipped else "0"
        report.append(f"| {path.name} | {read} | {written} | {skipped_text} |")
    rows.sort(key=_sort_key)
    report += ["", "Tables in the PSI folder with no mapper yet:", ""] + [f"- {name}" for name in unmapped]
    return rows, report


def write_catalog(path: Path) -> None:
    lines = ["# Data catalog — snapshot tables", "",
             "Generated by `scripts/build_snapshot.py` from `scripts/contract.py`. Do not edit by hand.", ""]
    for table, columns in contract.TABLES.items():
        lines += [f"## {table}", "", "| Column | Type | Unit | Meaning |", "|---|---|---|---|"]
        lines += [f"| `{c.name}` | {c.sql_type} | {c.unit} | {c.meaning} |" for c in columns]
        lines.append("")
    lines += ["## Caveats", ""] + [f"- {c}" for c in CAVEATS]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def build(psi_dir: Path, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows, report = build_tests(psi_dir)
    write_csv(out_dir / "tests.csv", contract.names(contract.TESTS), rows)
    write_catalog(out_dir / "catalog.md")
    (out_dir / "build-report.md").write_text(
        "# Snapshot build report\n\n" + "\n".join(report) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    build(PSI_DIR, SNAPSHOT_DIR)
    print(f"snapshot written to {SNAPSHOT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
